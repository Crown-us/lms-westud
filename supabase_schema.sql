CREATE POLICY "Students can mark lessons as complete." ON completed_lessons FOR INSERT WITH CHECK (auth.uid() = student_id);
CREATE POLICY "Students can unmark lessons as complete." ON completed_lessons FOR DELETE USING (auth.uid() = student_id);

-- Function to handle new user signup
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger AS $$
BEGIN
  INSERT INTO public.profiles (id, name, email, avatar_url, role)
  VALUES (new.id, new.raw_user_meta_data->>'name', new.email, new.raw_user_meta_data->>'avatar_url', 'siswa');
  RETURN new;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Trigger to call function on signup
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE PROCEDURE public.handle_new_user();

-- Function to increment course students
CREATE OR REPLACE FUNCTION public.increment_student_count()
RETURNS trigger AS $$
BEGIN
  UPDATE courses SET total_students = total_students + 1 WHERE id = new.course_id;
  RETURN new;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE TRIGGER on_enrollment_created
  AFTER INSERT ON enrollments
  FOR EACH ROW EXECUTE PROCEDURE public.increment_student_count();

-- Function to update enrollment progress
CREATE OR REPLACE FUNCTION public.update_enrollment_progress()
RETURNS trigger AS $$
DECLARE
  total_lessons INTEGER;
  done_lessons INTEGER;
  v_course_id BIGINT;
  v_student_id UUID;
BEGIN
  IF (TG_OP = 'DELETE') THEN
    v_course_id := old.course_id;
    v_student_id := old.student_id;
  ELSE
    v_course_id := new.course_id;
    v_student_id := new.student_id;
  END IF;

  -- Count total lessons in course
  SELECT COUNT(l.id) INTO total_lessons 
  FROM lessons l
  JOIN modules m ON l.module_id = m.id
  WHERE m.course_id = v_course_id;

  -- Count completed lessons by student
  SELECT COUNT(id) INTO done_lessons
  FROM completed_lessons
  WHERE student_id = v_student_id AND course_id = v_course_id;

  -- Update enrollment
  IF total_lessons > 0 THEN
    UPDATE enrollments 
    SET progress = ROUND((done_lessons::float / total_lessons::float) * 100)
    WHERE student_id = v_student_id AND course_id = v_course_id;
  END IF;

  RETURN NULL;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE TRIGGER on_lesson_completed
  AFTER INSERT OR DELETE ON completed_lessons
  FOR EACH ROW EXECUTE PROCEDURE public.update_enrollment_progress();

-- 12. Create Schedules Table
CREATE TABLE schedules (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES profiles(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  description TEXT,
  start_time TIMESTAMP WITH TIME ZONE NOT NULL,
  type TEXT DEFAULT 'Meet' CHECK (type IN ('Meet', 'Video', 'Live', 'Chat')),
  color TEXT DEFAULT 'bg-blue-500',
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 13. Create Private Chats Tables
CREATE TABLE chats (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
  last_message TEXT,
  last_message_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

CREATE TABLE chat_participants (
  chat_id UUID REFERENCES chats(id) ON DELETE CASCADE,
  user_id UUID REFERENCES profiles(id) ON DELETE CASCADE,
  PRIMARY KEY (chat_id, user_id)
);

CREATE TABLE messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chat_id UUID REFERENCES chats(id) ON DELETE CASCADE,
  sender_id UUID REFERENCES profiles(id) ON DELETE CASCADE,
  content TEXT NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- RLS for Schedules
ALTER TABLE schedules ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Users can manage their own schedules." ON schedules FOR ALL USING (auth.uid() = user_id);

-- RLS for Chats
ALTER TABLE chats ENABLE ROW LEVEL SECURITY;
ALTER TABLE chat_participants ENABLE ROW LEVEL SECURITY;
ALTER TABLE messages ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Participants can view their chats." ON chats FOR SELECT USING (
  EXISTS (SELECT 1 FROM chat_participants WHERE chat_id = id AND user_id = auth.uid())
);

CREATE POLICY "Participants can view other participants." ON chat_participants FOR SELECT USING (
  EXISTS (SELECT 1 FROM chat_participants cp WHERE cp.chat_id = chat_id AND cp.user_id = auth.uid())
);

CREATE POLICY "Participants can view messages." ON messages FOR SELECT USING (
  EXISTS (SELECT 1 FROM chat_participants WHERE chat_id = messages.chat_id AND user_id = auth.uid())
);

CREATE POLICY "Participants can send messages." ON messages FOR INSERT WITH CHECK (
  EXISTS (SELECT 1 FROM chat_participants WHERE chat_id = messages.chat_id AND user_id = auth.uid())
);
